const hear=(line,...cards)=>say('Послушай и посмотри на картинки.',line,cards,'listen',{
 samples:[{text:line}],adultPrompt:'Прочитайте текст вслух. Дайте ребёнку время рассмотреть картинки.',
});
const act=(prompt,line,...art)=>say(prompt,line,[token('act',visual(...art))],'act',{
 modeButton:'Сыграли вместе',result:token('show',visual(...art),{action:'touch'}),
});
